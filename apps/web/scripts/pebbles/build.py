#!/usr/bin/env python3
"""Render every pebble sprite in 3D and write them to src/assets/pebbles.

Needs Google Chrome (headless, loads three.js from jsDelivr) and Pillow.
    python3 apps/web/scripts/pebbles/build.py

render.html builds the scene (shape, matte material, lights, contact shadow, 3D eyes);
this script asks it for each variant, trims the transparent margins, records where
each pebble touches the floor, encodes WebP and regenerates index.ts.
"""
import base64
import html
import json
import os
import re
import subprocess
import tempfile
import urllib.parse
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "assets" / "pebbles"
COLORS = ["stone", "coral", "blue"]
EYES = ["open", "up", "closed", "x", "flat"]


def variants():
    v = []
    for c in COLORS:
        for e in EYES:
            v.append({"name": f"{c}-{e}", "color": c, "eyes": e})
            v.append({"name": f"icon-{c}-{e}", "color": c, "eyes": e, "icon": True, "eyeSize": 1.7})
    for n in (1, 3, 4, 5):
        v.append({"name": f"stone-open-cairn{n}", "color": "stone", "eyes": "open", "cairn": n, "lean": 0.4 if n > 3 else 0})
    return v


def render(batch):
    url = "file://" + str(HERE / "render.html") + "#" + urllib.parse.quote(json.dumps(batch))
    r = subprocess.run(
        ["google-chrome", "--headless=new", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--allow-file-access-from-files", "--virtual-time-budget=30000", "--dump-dom", url],
        capture_output=True, text=True, timeout=300,
    )
    m = re.search(r'<pre id="out">(.*?)</pre>', r.stdout, re.S)
    if not m or not m.group(1).strip():
        raise SystemExit("render failed:\n" + r.stderr[-2000:])
    return json.loads(html.unescape(m.group(1)))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name, r in render(variants()).items():
            png = Path(tmp) / f"{name}.png"
            png.write_bytes(base64.b64decode(r["png"].split(",")[1]))
            im = Image.open(png).convert("RGBA")
            alpha = im.split()[3]
            full = alpha.point(lambda a: 255 if a > 6 else 0).getbbox()
            body = alpha.point(lambda a: 255 if a > 235 else 0).getbbox()
            im = im.crop(full)
            # Icons only ever show small; board sprites stay sharp at 2x up to ~1.5x scale.
            target = 96 if name.startswith("icon-") else (480 if "cairn" in name else 320)
            f = min(1, target / im.size[0])
            im = im.resize((round(im.size[0] * f), round(im.size[1] * f)), Image.LANCZOS)
            im.save(OUT / f"{name}.webp", "WEBP", quality=88, method=6)
            meta[name] = {
                "w": im.size[0], "h": im.size[1],
                "ax": round((r["ax"] - full[0]) * f, 1), "ay": round((r["ay"] - full[1]) * f, 1),
                "bodyW": round((body[2] - body[0]) * f, 1),
            }
    keys = sorted(meta)
    ident = lambda k: k.replace("-", "_")
    lines = [
        "// Generated by scripts/pebbles/build.py from the 3D renders. Do not edit by hand.",
        "// ax/ay: where the pebble touches the floor, in image pixels. bodyW: the pebble's own width (cairn stones excluded).",
        "",
        *[f"import {ident(k)} from './{k}.webp'" for k in keys],
        "",
        "export type PebbleSprite = { src: string; w: number; h: number; ax: number; ay: number; bodyW: number }",
        "export const SPRITES = {",
        *[f"  '{k}': {{ src: {ident(k)}, w: {m['w']}, h: {m['h']}, ax: {m['ax']}, ay: {m['ay']}, bodyW: {m['bodyW']} }}," for k, m in ((k, meta[k]) for k in keys)],
        "} satisfies Record<string, PebbleSprite>",
        "export type SpriteKey = keyof typeof SPRITES",
    ]
    (OUT / "index.ts").write_text("\n".join(lines) + "\n")
    print(f"{len(keys)} sprites written to {OUT}")


if __name__ == "__main__":
    main()
